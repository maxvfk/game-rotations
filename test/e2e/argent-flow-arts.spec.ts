import {test,expect} from '@playwright/test';

const team='?team=argent-flow-arcane-gilberta-liino';
const tab=(page:import('@playwright/test').Page,name:string)=>page.locator('#tabs button').filter({has:page.locator('strong',{hasText:name})}).first();

test('Argent Flow Arts: unified cold buildup to burst and separate Cake Buster hot start',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(team);
 await expect(page.locator('#opener')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#tabs button')).toHaveCount(2);
 await expect(page.locator('.stage')).toHaveCount(3);
 await expect(page.locator('.stage-title').first()).toContainText('Накопление');
 await expect(page.locator('.stage-title').nth(1)).toContainText('по необходимости');
 await expect(page.locator('.stage-title').nth(2)).toContainText('Burst');
 await expect(page.locator('.action.arts-annotated')).toHaveCount(12);
 const sunder=page.locator('.stage').first().locator('.action.sunderization-annotated');
 await expect(sunder).toHaveCount(1);
 await expect(sunder.locator('.sunderization-gain-count')).toHaveText('+3');
 await expect(sunder.locator('.sunderization-gain')).toHaveAttribute('aria-label',/условный прирост, не итог/);
 const sunderIcon=sunder.locator('.sunderization-gain img');
 await expect(sunderIcon).toHaveAttribute('src',/effects\/arknights-endfield\/sunderization\.webp$/);
 await sunderIcon.scrollIntoViewIfNeeded();
 await expect.poll(()=>sunderIcon.evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBeGreaterThan(1);
 await expect(page.locator('.action-label').filter({hasText:'Bolt Rush: Electrification III'})).toHaveCount(1);
 const portrait=page.locator('.action').filter({hasText:'Bolt Rush: Electrification III'}).locator('.action-portrait');
 await portrait.scrollIntoViewIfNeeded();
 await expect(portrait).toHaveAttribute('src',/arknights-endfield\/argent-flow\.png$/);
 await expect.poll(()=>portrait.evaluate(node=>(node as HTMLImageElement).naturalWidth)).toBe(112);
 await page.locator('#control-pc').click();
 await expect(page.locator('.action').filter({hasText:'Stars Shifted: Electric Infliction I'}).locator('.keycap')).toHaveText('E');
 await expect(page.locator('.action').filter({hasText:'Vocalist Stance: лечение'}).locator('.keycap')).toHaveText('4');
 await expect(page.locator('.action').filter({hasText:'Создать новую Vulnerability'}).first().locator('.action-optional')).toHaveText('УСЛОВНО');
 await expect(page.locator('.stage').nth(1)).toContainText('Если Sunderization уже хватает');
 await page.locator('#loop').click();
 await expect(page.locator('.loop-warning')).toContainText('После финального Crush');
 await expect(page.locator('.stage')).toHaveCount(1);
 await expect(page.locator('.stage-title')).toContainText('Повтор burst не верифицирован');
 await page.locator('#opener').click();
 await expect(page.locator('.action-label').filter({hasText:'Heavens Sundered'})).toHaveCount(1);
 await expect(page.locator('.action').filter({hasText:'ДОП. ПАКЕТ'}).locator('.action-optional')).toHaveText('УСЛОВНО');
 await expect(page.locator('.action.optional-action')).toHaveCount(7);
 await expect(page.locator('.stage').nth(1).locator('.action.arts-annotated')).toHaveCount(3);
 await expect(page.locator('.stage').nth(2).locator('.action.arts-annotated')).toHaveCount(6);
 await expect(page.locator('.action').filter({hasText:'WILL Arcane → Electric II'}).locator('.action-optional')).toHaveCount(0);
 await expect(page.locator('.action').filter({hasText:'Если доп. пакет выбран: WILL Arcane'}).locator('.action-optional')).toHaveCount(0);
 await expect(page.locator('.action').filter({hasText:'Если доп. пакет выбран: Bolt Rush'}).locator('.action-optional')).toHaveCount(0);
 await page.locator('#layout-compact').click();
 await expect(page.locator('.sunderization-gain-count')).toHaveText('+3');
 await page.setViewportSize({width:320,height:740});
 const overflow=await page.evaluate(()=>{
  const viewport=document.documentElement.clientWidth;
  const elements=Array.from(document.querySelectorAll<HTMLElement>('.rotation-app *')).filter(node=>{
   const rect=node.getBoundingClientRect();
   return rect.width>0&&rect.right>viewport+1&&getComputedStyle(node).visibility!=='hidden';
  }).slice(0,10).map(node=>({tag:node.tagName,cls:node.className,text:node.textContent?.slice(0,40),right:Math.round(node.getBoundingClientRect().right)}));
  return {pixels:document.documentElement.scrollWidth-viewport,elements};
 });
 expect(overflow.pixels,JSON.stringify(overflow.elements)).toBeLessThanOrEqual(1);
 await page.screenshot({path:testInfo.outputPath('argent-sunderization-compact-320px.png'),fullPage:true,animations:'disabled'});
 await expect(page.locator('.sunderization-gain')).toHaveCount(5);
 await expect(page.locator('.sunderization-detonation')).toHaveCount(1);
 await expect(page.locator('.sunderization-gain-count')).toHaveText(['+3','+3','+3','+3','Detonation']);
 await tab(page,'Cake Buster').click();
 await expect(page.locator('#tabs button')).toHaveCount(2);
 await expect(page.locator('.action')).toHaveCount(9);
 await expect(page.locator('.sunderization-gain-count')).toHaveText(['+3','Detonation']);
 await expect(page.locator('.action.arts-annotated')).toHaveCount(7);
 await expect(page.locator('.action.optional-action')).toHaveCount(0);
 await expect(page.locator('.action-label').filter({hasText:'Nature Infliction'})).toHaveCount(1);
 await page.locator('#layout-compact').click();
 await expect(page.locator('.action-portrait')).toHaveCount(9);
 await page.setViewportSize({width:320,height:740});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
 await page.screenshot({path:testInfo.outputPath('argent-flow-arts-compact-320px.png'),fullPage:true,animations:'disabled'});
 expect(errors).toEqual([]);
});

test('Argent Flow: Arts toggle persists, local portraits work in offline PWA',async({page,context})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(team);
 await expect(page.locator('#arts-visibility-toggle')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('.stage')).toHaveCount(3);
 await expect(page.locator('.action.arts-annotated')).toHaveCount(12);
 await page.locator('#arts-visibility-toggle').click();
 await expect(page.locator('.arts-action-annotations')).toHaveCount(0);
 // Distinct Sunderization remains visible when Arts annotations are hidden.
 await expect(page.locator('.sunderization-gain')).toHaveCount(1);
 await page.locator('#arts-visibility-toggle').click();
 await expect(page.locator('.arts-action-annotations')).toHaveCount(12);
 await page.evaluate(async()=>{await navigator.serviceWorker.ready});
 await page.reload();
 await page.waitForFunction(()=>navigator.serviceWorker.controller!==null);
 await context.setOffline(true);
 await page.reload({waitUntil:'domcontentloaded'});
 await expect(page.locator('.action.arts-annotated')).toHaveCount(12);
 await expect(page.locator('.stage')).toHaveCount(3);
 const sunderOffline=page.locator('.sunderization-gain img');
 await expect(sunderOffline).toHaveCount(1);
 await sunderOffline.scrollIntoViewIfNeeded();
 await expect.poll(()=>sunderOffline.evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBeGreaterThan(1);
 const icon=page.locator('.action-portrait[src$="argent-flow.png"]').first();
 await icon.scrollIntoViewIfNeeded();
 await expect.poll(()=>icon.evaluate(el=>(el as HTMLImageElement).naturalWidth)).toBe(112);
 expect(errors).toEqual([]);
});
