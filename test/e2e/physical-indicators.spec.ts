import {test,expect} from '@playwright/test';
const url='?physical=arknights-endfield';
test('Physical gallery: original 1–4 Vulnerability stacks and four source-native effect glyphs (390/320 px)',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:390,height:844});await page.goto(url);
 await expect(page.locator('h1')).toHaveText('Физические статусы · Endfield');
 await expect(page.locator('.physical-stack-matrix .physical-vulnerability')).toHaveCount(4);
 await expect(page.locator('.physical-effect-matrix .physical-effect')).toHaveCount(4);
 await expect(page.locator('.arts-notice')).toContainText('не вычисляются из действий');
 await expect(page.locator('.physical-demo-row')).toHaveCount(2);
 const consumer=page.locator('.physical-demo-row').nth(1);
 await expect(consumer.locator('.physical-action-before .physical-vulnerability')).toHaveAttribute('data-stacks','3');
 await expect(consumer.locator('.physical-action-after .physical-vulnerability')).toHaveAttribute('data-stacks','0');
 await expect(consumer.locator('.physical-action-event .physical-effect')).toHaveAttribute('data-effect','breach');
 await expect(consumer.locator('.physical-action-effect')).toHaveAttribute('aria-label',/TEST/);
 const first=page.locator('.physical-stack-matrix img').first();
 await first.scrollIntoViewIfNeeded();await expect.poll(()=>first.evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBe(125);
 const lift=page.locator('.physical-effect-matrix img').first();
 await lift.scrollIntoViewIfNeeded();await expect.poll(()=>lift.evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBe(44);
 await page.screenshot({path:testInfo.outputPath('endfield-physical-gallery-390px.png'),fullPage:true,animations:'disabled'});
 await page.locator('[data-physical-size="32"]').click();
 await expect(page.locator('.physical-effect-matrix img').first()).toHaveAttribute('width','32');
 await page.locator('#physical-effect').selectOption('breach');
 await expect(page.locator('.physical-selected .physical-effect img')).toHaveAttribute('src',/breach\.webp$/);
 await page.locator('#physical-stacks').selectOption('unknown');
 await expect(page.locator('.physical-selected .physical-vulnerability img')).toHaveCount(0);
 await expect(page.locator('.physical-selected .arts-empty-mark')).toHaveText('?');
 await page.locator('#physical-stacks').selectOption('0');
 await expect(page.locator('.physical-selected .arts-empty-mark')).toHaveText('—');
 await page.setViewportSize({width:320,height:740});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
 await page.screenshot({path:testInfo.outputPath('endfield-physical-gallery-320px.png'),fullPage:true,animations:'disabled'});
 expect(errors).toEqual([]);
});
test('Physical gallery is reachable and original sprites work offline with WuWa/Arts preserved',async({page,context})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('');
 await expect(page.locator('a[href*="?physical=arknights-endfield"]')).toBeVisible();
 await page.locator('a[href*="?physical=arknights-endfield"]').click();
 await expect(page.locator('.physical-stack-matrix .physical-vulnerability')).toHaveCount(4);
 const img=page.locator('.physical-stack-matrix img').first();
 await img.scrollIntoViewIfNeeded();await expect.poll(()=>img.evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBe(125);
 const effect=page.locator('.physical-effect-matrix img').first();
 await effect.scrollIntoViewIfNeeded();await expect.poll(()=>effect.evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBe(44);
 await page.evaluate(async()=>{await navigator.serviceWorker.ready});await page.reload();
 await page.waitForFunction(()=>navigator.serviceWorker.controller!==null);
 await context.setOffline(true);await page.reload({waitUntil:'domcontentloaded'});
 await expect(page.locator('.physical-stack-matrix img')).toHaveCount(4);
 await expect.poll(()=>page.locator('.physical-stack-matrix img').first().evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBe(125);
 await expect.poll(()=>page.locator('.physical-effect-matrix img').first().evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBe(44);
 await context.setOffline(false);
 await page.goto('?arts=arknights-endfield');
 await expect(page.locator('.arts-stack-matrix .arts-infliction')).toHaveCount(16);
 await page.goto('?team=si-tangtang-arcane-xaihi');
 await expect(page.locator('.stage')).toHaveCount(3);
 await page.goto('?team=yyxl-suisui-chisa');
 await expect(page.locator('.physical-preview-root')).toHaveCount(0);
 expect(errors).toEqual([]);
});
